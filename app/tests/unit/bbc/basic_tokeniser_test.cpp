TEST(BasicTokeniserTest, AcceptsEachLineEndingAndSkipsBlankLines) {
  const Bytes expected = BasicTokeniser::Tokenise("10 PRINT\n20 END\n").Value();
  for (const char* source : {"10 PRINT\r\n20 END\r\n", "10 PRINT\r20 END",
                             "\n10 PRINT\n   \n20 END\n\n"}) {
    const StatusOr<Bytes> program = BasicTokeniser::Tokenise(source);
    ASSERT_TRUE(program.IsOk()) << source;
    EXPECT_EQ(*program, expected) << source;
  }
}

TEST(BasicTokeniserTest, AnEmptyProgramIsTheEndAlone) {
  EXPECT_EQ(BasicTokeniser::Tokenise("").Value(), (Bytes{0x0D, 0xFF}));
}

TEST(BasicTokeniserTest, RefusesLinesBasicWouldNotStore) {
  for (const char* source :
       {"PRINT", "10 PRINT\n10 END", "20 PRINT\n10 END", "32768 END", "10",
        "10 PRINT \"\xA3\"", "10 PRINT\t1"}) {
    const StatusOr<Bytes> program = BasicTokeniser::Tokenise(source);
    EXPECT_EQ(program.GetStatus().Code(), StatusCode::kInvalidArgument)
        << source;
  }
}

TEST(BasicTokeniserTest, RefusesALineTooLongOnceTokenised) {
  const std::string fits = "1 REM" + std::string(249, 'x');
  EXPECT_EQ(Line(fits).size(), 255U);
  EXPECT_FALSE(BasicTokeniser::Tokenise(fits + "x").IsOk());
}

